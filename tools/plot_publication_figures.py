def save_both(fig, out_dir, stem):
    import time
    for ext, kw in [("pdf", {"bbox_inches": "tight"}), ("png", {"dpi": 300, "bbox_inches": "tight"})]:
        fpath = os.path.join(out_dir, f"{stem}.{ext}")
        tmp_path = os.path.join(out_dir, f".{stem}.tmp.{ext}")
        fig.savefig(tmp_path, format=ext, **kw)
        for attempt in range(5):
            try:
                os.replace(tmp_path, fpath)
                break
            except OSError:
                time.sleep(0.15)
        else:
            os.replace(tmp_path, fpath)
    plt.close(fig)
    print(f"  -> Saved {stem}.{{pdf,png}}")


def read_csv_dicts(path):
    with open(path, "r", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def sig_stars(p):
    if p is None or (isinstance(p, float) and math.isnan(p)):
        return ""
    if p < 0.001:
        return "***"
    if p < 0.01:
        return "**"
    if p < 0.05:
        return "*"
    return "ns"


