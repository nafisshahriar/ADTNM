    q_rows = read_csv_dicts(os.path.join(data_dir, "env1_stress_audit_buffer_300s.csv"))

    tl_by_r = defaultdict(list)
    for r in tl_rows:
        tl_by_r[r["router"]].append(r)
    q_by_r = defaultdict(list)
    for r in q_rows:
        q_by_r[r["router"]].append(r)

    fig, axes = plt.subplots(4, 1, figsize=(7.3, 7.1), sharex=True, gridspec_kw={"hspace": 0.22})
    events = [(1.0, 3900/3600, "Ev A (5m)"), (2.0, 2.5, "Ev B (30m)"), (6.0, 8.0, "Event C (2h overload)")]

    for ax in axes:
        for s_h, e_h, _ in events:
            ax.axvspan(s_h, e_h, color="#D9D9D9", alpha=0.55, zorder=0)
        ax.grid(True)

